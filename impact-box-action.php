<?php

declare(strict_types=1);

session_start();

require_once __DIR__ . '/controllers/ImpactBoxController.php';


// =====================================================
// 1. XÁC ĐỊNH USER
// =====================================================
//
// Hiện tại hệ thống của bạn chưa hoàn thiện đăng nhập,
// nên tạm thời sử dụng user_id = 1 để kiểm tra.
//
// Khi phần đăng nhập hoàn thiện sẽ đổi thành:
// $userId = $_SESSION['user_id'];
//

$userId = 1;


// =====================================================
// 2. KHỞI TẠO CONTROLLER
// =====================================================

$controller = new ImpactBoxController();


// =====================================================
// 3. LẤY DỮ LIỆU TỪ FORM
// =====================================================

$action = $_POST['action'] ?? '';

$postId = (int) ($_POST['post_id'] ?? 0);


// =====================================================
// 4. KIỂM TRA POST ID
// =====================================================

if ($postId <= 0) {

    header('Location: views/impact-box.php');

    exit;
}


// =====================================================
// 5. XỬ LÝ CÁC CHỨC NĂNG
// =====================================================


/*
|--------------------------------------------------------------------------
| XÓA BÀI VIẾT KHỎI IMPACT BOX
|--------------------------------------------------------------------------
*/

if ($action === 'delete') {

    $controller->delete(
        $userId,
        $postId
    );
}


/*
|--------------------------------------------------------------------------
| THÊM / SỬA GHI CHÚ
|--------------------------------------------------------------------------
*/

elseif ($action === 'update_note') {

    $note = trim(
        $_POST['note'] ?? ''
    );

    $controller->updateNote(
        $userId,
        $postId,
        $note
    );
}


/*
|--------------------------------------------------------------------------
| XÓA GHI CHÚ
|--------------------------------------------------------------------------
*/

elseif ($action === 'clear_note') {

    $controller->clearNote(
        $userId,
        $postId
    );
}


// =====================================================
// 6. QUAY LẠI IMPACT BOX
// =====================================================

header(
    'Location: views/impact-box.php'
);

exit;